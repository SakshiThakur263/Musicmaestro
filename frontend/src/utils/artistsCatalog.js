export const findCatalogArtistBySlug = (slug) => {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();
  return (
    ARTISTS_CATALOG.find((a) => a.slug === normalized) ||
    ARTISTS_CATALOG.find(
      (a) =>
        a.name.toLowerCase().replace(/[^a-z0-9]+/g, '-') === normalized
    ) ||
    null
  );
};
